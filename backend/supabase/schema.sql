-- SmartCare Dental schema for Supabase PostgreSQL.
-- Run in the Supabase SQL Editor before importing application data.

CREATE TABLE IF NOT EXISTS public.schema_migrations (
  id TEXT PRIMARY KEY,
  applied_at TEXT NOT NULL DEFAULT to_char(CURRENT_TIMESTAMP, 'YYYY-MM-DD HH24:MI:SS')
);

CREATE TABLE IF NOT EXISTS public.users (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  role TEXT NOT NULL CHECK (role IN ('patient', 'clerk', 'dentist', 'admin')),
  email TEXT NOT NULL,
  password_hash TEXT NOT NULL,
  full_name TEXT NOT NULL,
  phone TEXT,
  is_demo INTEGER NOT NULL DEFAULT 0 CHECK (is_demo IN (0, 1)),
  active INTEGER NOT NULL DEFAULT 1,
  face_descriptor TEXT,
  face_descriptor_consent_at TEXT,
  created_at TEXT NOT NULL DEFAULT to_char(CURRENT_TIMESTAMP, 'YYYY-MM-DD HH24:MI:SS')
);
CREATE UNIQUE INDEX IF NOT EXISTS users_email_lower_unique ON public.users (lower(email));

CREATE TABLE IF NOT EXISTS public.patients (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code TEXT UNIQUE,
  user_id BIGINT UNIQUE REFERENCES public.users(id),
  full_name TEXT NOT NULL,
  birth_date TEXT,
  sex TEXT CHECK (sex IN ('female', 'male', 'other')),
  phone TEXT,
  email TEXT,
  address TEXT,
  emergency_contact TEXT,
  medical_notes TEXT,
  dentist_notes TEXT,
  is_demo INTEGER NOT NULL DEFAULT 0 CHECK (is_demo IN (0, 1)),
  created_by BIGINT REFERENCES public.users(id),
  created_at TEXT NOT NULL DEFAULT to_char(CURRENT_TIMESTAMP, 'YYYY-MM-DD HH24:MI:SS'),
  updated_at TEXT NOT NULL DEFAULT to_char(CURRENT_TIMESTAMP, 'YYYY-MM-DD HH24:MI:SS')
);
CREATE INDEX IF NOT EXISTS idx_patients_name ON public.patients (lower(full_name));

CREATE TABLE IF NOT EXISTS public.dentist_patient_notes (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  patient_id BIGINT NOT NULL REFERENCES public.patients(id) ON DELETE CASCADE,
  created_by BIGINT NOT NULL REFERENCES public.users(id),
  body TEXT NOT NULL CHECK (length(body) BETWEEN 1 AND 5000),
  created_at TEXT NOT NULL DEFAULT to_char(CURRENT_TIMESTAMP, 'YYYY-MM-DD HH24:MI:SS'),
  updated_at TEXT NOT NULL DEFAULT to_char(CURRENT_TIMESTAMP, 'YYYY-MM-DD HH24:MI:SS')
);
CREATE INDEX IF NOT EXISTS idx_dentist_notes_patient
  ON public.dentist_patient_notes (patient_id, created_at DESC, id DESC);

CREATE TABLE IF NOT EXISTS public.services (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL UNIQUE,
  category TEXT NOT NULL,
  description TEXT NOT NULL DEFAULT '',
  price_php INTEGER NOT NULL CHECK (price_php >= 0),
  duration_min INTEGER NOT NULL CHECK (duration_min > 0),
  prep_guidelines TEXT NOT NULL DEFAULT '',
  active INTEGER NOT NULL DEFAULT 1,
  created_at TEXT NOT NULL DEFAULT to_char(CURRENT_TIMESTAMP, 'YYYY-MM-DD HH24:MI:SS')
);

CREATE TABLE IF NOT EXISTS public.dentists (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL UNIQUE REFERENCES public.users(id),
  specialty TEXT NOT NULL DEFAULT 'General Dentistry',
  bio TEXT NOT NULL DEFAULT '',
  status TEXT NOT NULL DEFAULT 'available' CHECK (status IN ('available', 'on_break', 'off_duty')),
  active INTEGER NOT NULL DEFAULT 1
);

CREATE TABLE IF NOT EXISTS public.dentist_schedules (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  dentist_id BIGINT NOT NULL REFERENCES public.dentists(id) ON DELETE CASCADE,
  weekday INTEGER NOT NULL CHECK (weekday BETWEEN 0 AND 6),
  start_time TEXT NOT NULL,
  end_time TEXT NOT NULL,
  CHECK (start_time < end_time)
);
CREATE INDEX IF NOT EXISTS idx_sched_dentist ON public.dentist_schedules (dentist_id, weekday);

CREATE TABLE IF NOT EXISTS public.dentist_time_off (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  dentist_id BIGINT NOT NULL REFERENCES public.dentists(id) ON DELETE CASCADE,
  date TEXT NOT NULL,
  reason TEXT,
  UNIQUE (dentist_id, date)
);

CREATE TABLE IF NOT EXISTS public.appointments (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  reference TEXT NOT NULL UNIQUE,
  patient_id BIGINT NOT NULL REFERENCES public.patients(id),
  dentist_id BIGINT NOT NULL REFERENCES public.dentists(id),
  service_id BIGINT NOT NULL REFERENCES public.services(id),
  date TEXT NOT NULL,
  start_time TEXT NOT NULL,
  end_time TEXT NOT NULL,
  status TEXT NOT NULL DEFAULT 'pending'
    CHECK (status IN ('pending', 'confirmed', 'declined', 'cancelled', 'completed', 'no_show')),
  source TEXT NOT NULL DEFAULT 'online_portal'
    CHECK (source IN ('online_portal', 'walk_in', 'messenger')),
  notes TEXT,
  status_reason TEXT,
  created_by BIGINT REFERENCES public.users(id),
  created_at TEXT NOT NULL DEFAULT to_char(CURRENT_TIMESTAMP, 'YYYY-MM-DD HH24:MI:SS'),
  updated_at TEXT NOT NULL DEFAULT to_char(CURRENT_TIMESTAMP, 'YYYY-MM-DD HH24:MI:SS')
);
CREATE INDEX IF NOT EXISTS idx_appt_dentist_date ON public.appointments (dentist_id, date, status);
CREATE INDEX IF NOT EXISTS idx_appt_patient ON public.appointments (patient_id, date);
CREATE INDEX IF NOT EXISTS idx_appt_date ON public.appointments (date);

CREATE TABLE IF NOT EXISTS public.dentist_reviews (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  appointment_id BIGINT NOT NULL UNIQUE REFERENCES public.appointments(id) ON DELETE CASCADE,
  patient_id BIGINT NOT NULL REFERENCES public.patients(id),
  dentist_id BIGINT NOT NULL REFERENCES public.dentists(id),
  rating INTEGER NOT NULL CHECK (rating BETWEEN 1 AND 5),
  comment TEXT NOT NULL DEFAULT '' CHECK (length(comment) <= 1000),
  is_public INTEGER NOT NULL DEFAULT 0 CHECK (is_public IN (0, 1)),
  created_at TEXT NOT NULL DEFAULT to_char(CURRENT_TIMESTAMP, 'YYYY-MM-DD HH24:MI:SS')
);
CREATE INDEX IF NOT EXISTS idx_dentist_reviews_public
  ON public.dentist_reviews (dentist_id, is_public, created_at DESC);

CREATE TABLE IF NOT EXISTS public.appointment_payments (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  appointment_id BIGINT NOT NULL UNIQUE REFERENCES public.appointments(id) ON DELETE CASCADE,
  provider_checkout_id TEXT NOT NULL UNIQUE,
  checkout_url TEXT NOT NULL,
  amount_centavos INTEGER NOT NULL CHECK (amount_centavos > 0),
  status TEXT NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'paid', 'expired', 'failed')),
  paid_at TEXT,
  created_at TEXT NOT NULL DEFAULT to_char(CURRENT_TIMESTAMP, 'YYYY-MM-DD HH24:MI:SS'),
  updated_at TEXT NOT NULL DEFAULT to_char(CURRENT_TIMESTAMP, 'YYYY-MM-DD HH24:MI:SS')
);

CREATE TABLE IF NOT EXISTS public.payment_transactions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  appointment_id BIGINT NOT NULL UNIQUE REFERENCES public.appointments(id) ON DELETE CASCADE,
  provider_checkout_id TEXT NOT NULL,
  provider_payment_id TEXT UNIQUE,
  amount_paid_centavos INTEGER NOT NULL CHECK (amount_paid_centavos > 0),
  status TEXT NOT NULL CHECK (status IN ('paid')),
  paid_at TEXT NOT NULL DEFAULT to_char(CURRENT_TIMESTAMP, 'YYYY-MM-DD HH24:MI:SS'),
  created_at TEXT NOT NULL DEFAULT to_char(CURRENT_TIMESTAMP, 'YYYY-MM-DD HH24:MI:SS')
);

CREATE TABLE IF NOT EXISTS public.appointment_counter_payments (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  appointment_id BIGINT NOT NULL UNIQUE REFERENCES public.appointments(id) ON DELETE CASCADE,
  amount_centavos INTEGER NOT NULL CHECK (amount_centavos > 0),
  received_by BIGINT NOT NULL REFERENCES public.users(id),
  received_at TEXT NOT NULL DEFAULT to_char(CURRENT_TIMESTAMP, 'YYYY-MM-DD HH24:MI:SS')
);

CREATE TABLE IF NOT EXISTS public.slot_holds (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL REFERENCES public.users(id),
  dentist_id BIGINT NOT NULL REFERENCES public.dentists(id),
  date TEXT NOT NULL,
  start_time TEXT NOT NULL,
  end_time TEXT NOT NULL,
  expires_at BIGINT NOT NULL
);

CREATE TABLE IF NOT EXISTS public.conversations (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  patient_id BIGINT NOT NULL REFERENCES public.patients(id),
  dentist_id BIGINT NOT NULL REFERENCES public.dentists(id),
  created_at TEXT NOT NULL DEFAULT to_char(CURRENT_TIMESTAMP, 'YYYY-MM-DD HH24:MI:SS'),
  last_message_at TEXT,
  UNIQUE (patient_id, dentist_id)
);

CREATE TABLE IF NOT EXISTS public.messages (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  conversation_id BIGINT NOT NULL REFERENCES public.conversations(id) ON DELETE CASCADE,
  sender_user_id BIGINT NOT NULL REFERENCES public.users(id),
  body TEXT NOT NULL,
  read_at TEXT,
  created_at TEXT NOT NULL DEFAULT to_char(CURRENT_TIMESTAMP, 'YYYY-MM-DD HH24:MI:SS'),
  updated_at TEXT
);
CREATE INDEX IF NOT EXISTS idx_msg_conv ON public.messages (conversation_id, id);

CREATE TABLE IF NOT EXISTS public.message_images (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  conversation_id BIGINT NOT NULL REFERENCES public.conversations(id) ON DELETE CASCADE,
  message_id BIGINT NOT NULL UNIQUE REFERENCES public.messages(id) ON DELETE CASCADE,
  file_name TEXT NOT NULL,
  content_type TEXT NOT NULL CHECK (content_type IN ('image/jpeg', 'image/png', 'image/webp')),
  byte_size INTEGER NOT NULL CHECK (byte_size BETWEEN 1 AND 5242880),
  image_data BYTEA NOT NULL,
  created_at TEXT NOT NULL DEFAULT to_char(CURRENT_TIMESTAMP, 'YYYY-MM-DD HH24:MI:SS')
);

